/** Реквизиты оператора площадки — из окружения сервера; пока не заданы, документы помечены как черновик. */
export function operator() {
  const env = (k: string) => process.env[k]?.trim() || null;
  const o = {
    name: env('OPERATOR_NAME'),
    inn: env('OPERATOR_INN'),
    ogrn: env('OPERATOR_OGRN'),
    address: env('OPERATOR_ADDRESS'),
    email: env('OPERATOR_EMAIL'),
  };
  return { ...o, complete: Object.values(o).every(Boolean) };
}

